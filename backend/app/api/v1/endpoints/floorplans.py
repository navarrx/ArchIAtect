from fastapi import APIRouter, Depends, Query, HTTPException
from sqlalchemy.orm import Session
from app.services.generation_service import get_all_floorplans, get_recent_floorplans
from app.db.session import get_db
from app.schemas.generation import GenerationResponse
from typing import List, Optional
from app.api.deps import get_current_user
from app.db import crud
from datetime import datetime, timedelta
from sqlalchemy import desc, asc, func
from app.models.user import User

router = APIRouter()

@router.get("/", response_model=List[GenerationResponse])
def read_floorplans(
    db: Session = Depends(get_db),
    page: int = Query(1, ge=1),  
    limit: int = Query(20, le=50),
    sort: str = Query("newest", regex="^(newest|oldest)$"),
    date: Optional[str] = None,
):
    """
    Get all floor plans with pagination, sorting and date filtering.
    """
    skip = (page - 1) * limit
    
    # Base query
    query = db.query(crud.Generation)
    
    # Apply date filter if provided
    if date:
        try:
            filter_date = datetime.strptime(date, "%Y-%m-%d").date()
            # Filter for the specific day by using the start and end of the day
            start_of_day = datetime.combine(filter_date, datetime.min.time())
            end_of_day = datetime.combine(filter_date, datetime.max.time())
            query = query.filter(
                crud.Generation.created_at >= start_of_day,
                crud.Generation.created_at <= end_of_day
            )
        except ValueError:
            raise HTTPException(status_code=400, detail="Invalid date format. Use YYYY-MM-DD")
    
    # Apply sorting
    if sort == "newest":
        query = query.order_by(desc(crud.Generation.created_at))
    else:
        query = query.order_by(asc(crud.Generation.created_at))
    
    # Apply pagination
    generations = query.offset(skip).limit(limit).all()
    
    return [
        GenerationResponse(
            id=g.id,
            prompt=g.prompt,
            layout_image_url=g.layout_image_url,
            sd_image_url=g.sd_image_url,
            created_at=g.created_at,
            status=g.status,
            error_message=g.error_message
        )
        for g in generations
    ]

